-- Run in Supabase > SQL Editor.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  status text not null default 'pending' check (status in ('pending','approved','blocked')),
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles(id,email,status)
  values(new.id,new.email,'pending')
  on conflict(id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  title text not null,
  description text default '',
  storage_path text not null unique,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.videos enable row level security;

drop policy if exists "read own profile" on public.profiles;
create policy "read own profile" on public.profiles
for select to authenticated using (auth.uid() = id);

drop policy if exists "approved users read videos" on public.videos;
create policy "approved users read videos" on public.videos
for select to authenticated using (
  exists(select 1 from public.profiles p where p.id=auth.uid() and p.status='approved')
);

-- Create a PRIVATE bucket named private-videos in Storage first.
drop policy if exists "approved users read private bucket" on storage.objects;
create policy "approved users read private bucket" on storage.objects
for select to authenticated using (
  bucket_id='private-videos' and exists(
    select 1 from public.profiles p where p.id=auth.uid() and p.status='approved'
  )
);

